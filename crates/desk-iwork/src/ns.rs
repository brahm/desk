//! The namespaces of iWork '09.

/// The vocabulary shared by the three apps.
pub const SF: &str = "http://developer.apple.com/namespaces/sf";
/// Attributes of the shared vocabulary, such as IDs and values.
pub const SFA: &str = "http://developer.apple.com/namespaces/sfa";
/// Pages ("SL", from the code name Slingshot).
pub const SL: &str = "http://developer.apple.com/namespaces/sl";
/// Numbers ("LS").
pub const LS: &str = "http://developer.apple.com/namespaces/ls";
/// Keynote ("KEY").
pub const KEY: &str = "http://developer.apple.com/namespaces/keynote2";
